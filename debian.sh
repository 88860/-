#!/bin/bash
# debian13自用 - Debian 13 自用一键菜单
# 1 = 安装 XanMod LTS 内核并自动重启
# 2 = 一键配置
# 3 = 一键 DD 全新 Debian

set -Eeuo pipefail

SCRIPT_NAME="debian13自用"

# ============================================================
# 临时目录
# ============================================================

TMP_DIR="$(mktemp -d /tmp/debian13-self.XXXXXX)"

trap 'rm -rf "$TMP_DIR"' EXIT


# ============================================================
# 这里留给你自己填写
# ============================================================

KERNEL_B64=""

STEP2_B64=""

STEP3_B64=""

STEP4_B64=""

STEP5_B64=""

STEP6_B64=""


# ============================================================
# 检查 root
# ============================================================

need_root() {
    if [[ "${EUID}" -ne 0 ]]; then
        echo "错误：请使用 root 运行。"
        exit 1
    fi
}


# ============================================================
# 执行 Base64 脚本
# ============================================================

run_b64() {
    local num="$1"
    local data="$2"
    local file

    file="$TMP_DIR/${num}.sh"

    printf '%s' "$data" | base64 -d > "$file"

    chmod 700 "$file"

    echo
    echo "============================================================"
    echo "正在执行：$num"
    echo "============================================================"

    bash "$file"
}


# ============================================================
# 1. 安装 XanMod LTS 内核
# ============================================================

install_kernel() {

    echo "============================================================"
    echo " 1. 安装 XanMod LTS 内核"
    echo "============================================================"
    echo "将执行你提供的 1 换内核脚本；成功后自动重启。"
    echo

    read -r -p "确认安装内核并自动重启？[y/N] " ans

    case "$ans" in
        y|Y|yes|YES)
            ;;
        *)
            echo "已取消。"
            return 0
            ;;
    esac

    local file="$TMP_DIR/1.sh"

    printf '%s' "$KERNEL_B64" | base64 -d > "$file"

    chmod 700 "$file"

    bash "$file"

    echo
    echo "============================================================"
    echo "内核安装命令执行成功"
    echo "5 秒后自动重启..."
    echo "============================================================"

    sleep 5

    systemctl reboot
}


# ============================================================
# 2. 一键配置
# ============================================================

run_all() {

    echo "============================================================"
    echo " 2. 一键配置"
    echo "============================================================"
    echo "注意：2 会删除旧内核/元包；3 会删除 qemu*、os-prober、"
    echo "laptop-detect、pciutils、dmidecode 等软件及依赖。"
    echo

    read -r -p "确认开始执行？[y/N] " ans

    case "$ans" in
        y|Y|yes|YES)
            ;;
        *)
            echo "已取消。"
            return 0
            ;;
    esac


    # --------------------------------------------------------
    # 步骤 2
    # --------------------------------------------------------

    run_b64 "2" "$STEP2_B64"


    # --------------------------------------------------------
    # 步骤 3
    # --------------------------------------------------------

    run_b64 "3" "$STEP3_B64"


    # --------------------------------------------------------
    # 步骤 4
    # --------------------------------------------------------

    run_b64 "4" "$STEP4_B64"


    # --------------------------------------------------------
    # 步骤 5
    # --------------------------------------------------------

    run_b64 "5" "$STEP5_B64"


    # --------------------------------------------------------
    # 步骤 6
    # --------------------------------------------------------

    run_b64 "6" "$STEP6_B64"


    echo
    echo "============================================================"
    echo "已全部执行完成。"
    echo "============================================================"
}


# ============================================================
# 3. 一键 DD 为全新 Debian
# ============================================================

dd_debian() {

    echo "============================================================"
    echo " 3. 一键 DD 为全新 Debian"
    echo "============================================================"
    echo
    echo "警告：此操作会重装系统并清除当前系统数据。"
    echo "请确认你已经做好数据备份。"
    echo

    read -r -p "确认继续 DD？请输入 y/Y：" ans

    if [[ ! "$ans" =~ ^[Yy]$ ]]; then
        echo "已取消。"
        return 0
    fi


    # --------------------------------------------------------
    # 下载 reinstall.sh
    # --------------------------------------------------------

    echo
    echo "============================================================"
    echo "开始下载 reinstall.sh..."
    echo "============================================================"

    local reinstall_script="$TMP_DIR/reinstall.sh"


    if command -v curl >/dev/null 2>&1; then

        curl -fL \
            -o "$reinstall_script" \
            "https://raw.githubusercontent.com/bin456789/reinstall/main/reinstall.sh"

    elif command -v wget >/dev/null 2>&1; then

        wget \
            -O "$reinstall_script" \
            "https://raw.githubusercontent.com/bin456789/reinstall/main/reinstall.sh"

    else

        echo "错误：系统中没有 curl 或 wget。"
        return 1

    fi


    # --------------------------------------------------------
    # 检查下载结果
    # --------------------------------------------------------

    if [[ ! -s "$reinstall_script" ]]; then
        echo "错误：reinstall.sh 下载失败。"
        return 1
    fi


    chmod 700 "$reinstall_script"


    echo
    echo "============================================================"
    echo "reinstall.sh 下载成功"
    echo "============================================================"

    sleep 2


    # --------------------------------------------------------
    # 开始 DD
    # --------------------------------------------------------

    echo
    echo "============================================================"
    echo "开始 DD Debian..."
    echo "============================================================"
    echo

    bash "$reinstall_script" debian


    # --------------------------------------------------------
    # DD 脚本正常返回后自动重启
    # --------------------------------------------------------

    echo
    echo "============================================================"
    echo "DD 命令执行结束"
    echo "============================================================"
    echo
    echo "3 秒后自动重启..."
    echo

    sleep 3

    systemctl reboot
}


# ============================================================
# 菜单
# ============================================================

show_menu() {

    clear 2>/dev/null || true

    echo "============================================================"
    echo "                 $SCRIPT_NAME"
    echo "============================================================"
    echo
    echo "  1. 换内核（XanMod LTS）→ 成功后自动重启"
    echo "  2. 一键配置"
    echo "  3. 一键 DD 为全新 Debian"
    echo "  0. 退出"
    echo
    echo "============================================================"
}


# ============================================================
# 主程序
# ============================================================

need_root


while true; do

    show_menu

    read -r -p "请选择 [0-3]：" choice

    case "$choice" in

        1)
            install_kernel
            ;;

        2)
            run_all
            ;;

        3)
            dd_debian
            ;;

        0)
            echo "退出。"
            exit 0
            ;;

        *)
            echo "无效选择。"
            sleep 1
            ;;

    esac


    echo

    read -r -p "按回车返回菜单..." _

done
